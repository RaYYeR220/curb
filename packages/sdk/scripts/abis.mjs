// Regenerates src/abis.ts from the Foundry build and src/deployments.ts from deployments/4663.json.
// Run `forge build` at the repository root first.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const root = new URL("../../../", import.meta.url);
const abiOf = (name) => JSON.parse(readFileSync(new URL(`out/${name}.sol/${name}.json`, root), "utf8")).abi;

const wrappedError = abiOf("CustomRevert").filter((x) => x.type === "error" && x.name === "WrappedError");

const entries = {
  curbHookAbi: abiOf("CurbHook"),
  curbDeskAbi: abiOf("CurbDesk"),
  curbRouterAbi: abiOf("CurbRouter"),
  wrappedErrorAbi: wrappedError,
};

let out = "// Generated by scripts/abis.mjs from the Foundry build. Do not edit.\n\n";
for (const [name, abi] of Object.entries(entries)) {
  out += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(new URL("../src/abis.ts", import.meta.url), out);

const deploymentsFile = new URL("deployments/4663.json", root);
const deployments = existsSync(deploymentsFile) ? JSON.parse(readFileSync(deploymentsFile, "utf8")) : {};
writeFileSync(
  new URL("../src/deployments.ts", import.meta.url),
  "// Generated by scripts/abis.mjs from deployments/4663.json. Do not edit.\n\n" +
    `export const deployments = ${JSON.stringify(deployments, null, 2)} as const;\n`,
);
console.log("abis:", Object.keys(entries).join(", "));
